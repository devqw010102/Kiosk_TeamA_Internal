package kr.hcnc.vo;

public class EduInfoVO {
	private String eduId;
	private String enuName;
	private String startDate;
	private String endDate;
	private String eduRoomName;
	private String delYn;
	
	public String getEduId() {
		return eduId;
	}
	public void setEduId(String eduId) {
		this.eduId = eduId;
	}
	public String getEnuName() {
		return enuName;
	}
	public void setEnuName(String enuName) {
		this.enuName = enuName;
	}
	public String getStartDate() {
		return startDate;
	}
	public void setStartDate(String startDate) {
		this.startDate = startDate;
	}
	public String getEndDate() {
		return endDate;
	}
	public void setEndDate(String endDate) {
		this.endDate = endDate;
	}
	public String getEduRoomName() {
		return eduRoomName;
	}
	public void setEduRoomName(String eduRoomName) {
		this.eduRoomName = eduRoomName;
	}
	public String getDelYn() {
		return delYn;
	}
	public void setDelYn(String delYn) {
		this.delYn = delYn;
	}
	
	
}
